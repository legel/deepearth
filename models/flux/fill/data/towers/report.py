"""Dataset statistics and sampling weights, written to <out>/report.json, <out>/weights.parquet and into the
dataset card (README.md, between the report markers).

Sampling weights. Sites are not evenly spread over ecosystems and climates (many temperate forests and croplands in
Europe and North America, few tropical, arid and polar sites). A site's weight is inversely proportional to the
number of included sites in its stratum (IGBP group x Koppen main class), normalised to a mean of 1 over the
training sites and capped at WEIGHT_CAP. A window's weight is its site's weight divided by the site's number of
usable windows, so a long record does not outweigh a short one from a rarer stratum.

    python report.py --out /home/photon/4tb/fluxfill/towers
"""

import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

from split import IGBP_GROUP

WEIGHT_CAP = 5.0
CARD = Path(__file__).with_name("README.md")
START, END = "<!-- report:start -->", "<!-- report:end -->"


def table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def du(path: Path, pattern: str) -> float:
    return sum(p.stat().st_size for p in path.glob(pattern)) / 1e9


def build(out: Path, card: bool = True) -> dict:
    s = pd.read_parquet(out / "sites.parquet")
    inc = s[s.included].copy()
    sp = pd.read_csv(out / "split.csv") if (out / "split.csv").exists() else None
    if sp is not None:
        inc = inc.merge(sp[["site_id", "split"]], on="site_id", how="left")
    counts = pd.read_parquet(out / "qc_counts.parquet")
    cov = pd.read_parquet(out / "coverage.parquet")
    win = pd.read_parquet(out / "windows.parquet")
    ev = pd.read_parquet(out / "events.parquet")
    inc["igbp_group"] = inc.igbp.map(IGBP_GROUP).fillna("other")
    inc["stratum"] = inc.igbp_group + "|" + inc.koppen_main.fillna("?")
    n = inc.stratum.map(inc.stratum.value_counts())
    w = 1.0 / n
    train = inc.split.isin(["train", "val"]) if "split" in inc else np.ones(len(inc), bool)
    w = np.minimum(w / w[train].mean(), WEIGHT_CAP)
    uw = win[win.usable].groupby("site_id").size()
    weights = pd.DataFrame({"site_id": inc.site_id, "stratum": inc.stratum, "site_weight": w.round(4),
                            "usable_windows": inc.site_id.map(uw).fillna(0).astype(int)})
    weights["window_weight"] = (weights.site_weight / weights.usable_windows.clip(lower=1)).round(6)
    weights.to_parquet(out / "weights.parquet", index=False)

    rules = ["filled", "quality", "range", "stuck", "spike", "ustar", "site"]
    by_rule = counts.groupby("variable")[["measured_at_source", *rules, "final"]].sum()
    by_rule = by_rule.loc[[v for v in ["NEE", "LE", "H", "FCH4", "G", "TA", "SW_IN", "LW_IN", "VPD", "RH", "PA", "P",
                                       "WS", "USTAR", "NETRAD", "PPFD_IN", "TS_1", "SWC_1", "WTD"] if v in by_rule.index]]
    lat_band = pd.cut(inc.lat.astype(float), [-90, -23.5, 0, 23.5, 35, 50, 66.5, 90],
                      labels=["<23.5S", "23.5S-0", "0-23.5N", "23.5-35N", "35-50N", "50-66.5N", ">66.5N"])
    split_col = "split" if "split" in inc else None

    def dist(col):
        g = inc.groupby([col] + ([split_col] if split_col else [])).size().unstack(fill_value=0) if split_col \
            else inc.groupby(col).size().to_frame("sites")
        g["all"] = g.sum(axis=1)
        return g.sort_values("all", ascending=False).reset_index()

    inc["lat_band"] = lat_band
    rep = {
        "sites_candidate": int(len(s)), "sites_included": int(len(inc)),
        "sites_with_fch4": int(inc.has_fch4.sum()), "hourly_sites": int((inc.step_min == 60).sum()),
        "usable_windows": int(win.usable.sum()), "windows": int(len(win)),
        "split": inc[split_col].value_counts().to_dict() if split_col else {},
        "split_fch4": inc[inc.has_fch4][split_col].value_counts().to_dict() if split_col else {},
        "measured_values": {v: int(by_rule.loc[v, "final"]) for v in by_rule.index},
        "events": ev.kind.value_counts().to_dict(),
        "size_gb": {"hh": round(du(out, "hh/*.parquet"), 2), "interim": round(du(out, "interim/*/*.parquet"), 2)},
    }
    (out / "report.json").write_text(json.dumps(rep, indent=1, default=str))
    md = [f"Generated by `report.py` from the build in `{out}`.", "",
          f"- Candidate sites: {rep['sites_candidate']}. Included (at least one usable 180-day window): "
          f"{rep['sites_included']}. With measured FCH4: {rep['sites_with_fch4']}. Hourly records: "
          f"{rep['hourly_sites']}.",
          f"- Windows (180 d, 30-d stride): {rep['windows']}, of which usable: {rep['usable_windows']}.",
          f"- Split (sites): {rep['split']}. FCH4 sites: {rep['split_fch4']}.",
          f"- Size: per-site tables {rep['size_gb']['hh']} GB, interim tables {rep['size_gb']['interim']} GB.", "",
          "Values removed per rule, summed over sites and sources (each value counted under the first rule that "
          "removes it; `filled` counts source gap-fills, never stored):", "",
          table(by_rule.reset_index()), "", "Events recorded (events.parquet):", "",
          table(ev.kind.value_counts().rename_axis("kind").reset_index(name="count")), "",
          "Sites by IGBP class:", "", table(dist("igbp")), "", "Sites by Koppen main class:", "",
          table(dist("koppen_main")), "", "Sites by latitude band:", "", table(dist("lat_band")), "",
          "Sites by data hub:", "", table(dist("data_hub")), "",
          "Strata with the largest and smallest sampling weights:", "",
          table(weights.groupby("stratum").agg(sites=("site_id", "size"), site_weight=("site_weight", "first"))
                .sort_values("site_weight").reset_index().iloc[np.r_[0:5, -5:0]] if len(weights) > 10 else
                weights.groupby("stratum").size().reset_index(name="sites"))]
    text = CARD.read_text()
    if card and START in text and END in text:
        text = re.sub(re.escape(START) + ".*?" + re.escape(END), START + "\n" + "\n".join(md) + "\n" + END, text,
                      flags=re.S)
        CARD.write_text(text)
    (out / "report.md").write_text("\n".join(md) + "\n")
    return rep


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--no-card", action="store_true", help="do not write the statistics into README.md")
    a = ap.parse_args()
    print(json.dumps(build(a.out, not a.no_card), indent=1, default=str))


if __name__ == "__main__":
    main()
