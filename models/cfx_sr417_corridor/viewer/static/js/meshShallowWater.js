import * as THREE from 'three';
import { OBJLoader } from 'three/addons/loaders/OBJLoader.js';
import { createDropletFlow } from './dropletFlow.js';

/**
 * createMeshShallowWater() → { group, tick(dt), setSpeed(x), setExag(newExag) }
 *
 * Renders simulation/mesh_shallow_water.py's output — the real 3D local-inertial
 * shallow-water solver on the fused ground+roof mesh (see that script's docstring). Three
 * synced pieces, all driven by the same solve:
 *
 *   1. Falling rain particles spawned above the mesh that descend and land at the REAL
 *      surface height (roof or ground) via a nearest-cell lookup into the heightmap the
 *      Python script exports — not a flat plane. Particle count is driven by the same
 *      synthetic rain hyetograph the solver used, so visual rain intensity tracks what's
 *      actually forcing the depth field at that point in the loop.
 *   2. Physics-driven flow tracers (2026-07-21) — replaces the earlier standalone droplet
 *      layer's role entirely. Reuses dropletFlow.js's proven rendering (trail + moving point,
 *      3-way settle/runoff/still-moving color) completely unchanged, just pointed at
 *      flow_tracer_paths.bin: paths generated by mesh_shallow_water.py's run_flow_tracers,
 *      which advects particles using the solver's own reconstructed velocity field instead
 *      of a fixed step — fast on an actively-draining roof, slow/stopped in a real puddle —
 *      with a synthetic sky-fall lead-in and start times staggered across the real rain
 *      event. This is the primary "watch it flow" visual; it supersedes the older fixed-step
 *      droplet layer, which is no longer shown alongside it.
 *   3. A depth-film overlay on the SAME triangle mesh dense_test_area_mesh.obj already
 *      uses (loaded again here as an independent copy so it can carry its own per-triangle
 *      vertex colors) — additive-blended, so dry triangles (color -> black) are effectively
 *      invisible and only wet ones glow blue, intensity by depth. Kept as a secondary cue
 *      for the aggregate depth/lake-level story (the tracers show individual paths, not "how
 *      deep is it right now everywhere"); depth also lifts the film slightly above the
 *      surface, exaggerated an EXTRA `DEPTH_VISUAL_SCALE`x — a demo-scale visibility choice,
 *      not a physical claim; see mesh_shallow_water.py for the real depth values in meters.
 *      IMPORTANT: unlike other LiDAR mesh layers, main.js must drive exaggeration via the
 *      returned setExag(newExag) — NOT the generic rescaleY(mesh, ratio) transform — because
 *      applyFrame() rebuilds every vertex from source arrays each time the visible frame
 *      changes; a one-shot external mesh transform gets silently undone on the next frame.
 *      setExag() rescales the actual source arrays (basePos, the heightmap, in-flight rain,
 *      and the tracer sub-layer) in place instead — see the currentVertExag comment below.
 *
 * Binary formats (see mesh_shallow_water.py):
 *   MSWE: 'MSWE' + uint32 n_tri, uint32 n_frames, uint8[n_tri] is_roof,
 *         float32[n_frames] times_s, then per frame float32[n_tri] depth_m
 *   HMAP: 'HMAP' + int32 nx, int32 ny, float32 sx0, sx1, sz0, sz1,
 *         float32[ny*nx] scene-space surface height (row-major, y then x)
 *   DROP (flow tracers): see dropletFlow.js
 */
// Visual tuning (2026-07-20, per request): real depths here are physically thin (ground
// peaks ~16cm, roof capped ~28cm — see mesh_shallow_water.py's summary), which read as barely-
// there at the original SAT_DEPTH=0.12/DEPTH_VISUAL_SCALE=15. Lowering the saturation depth and
// raising the visual scale trades literal 1:1 fidelity for demo legibility — the numbers behind
// it (mass balance, depths) are unchanged and still reportable as-is; this only affects how the
// existing physics renders on screen.
const DEPTH_VISUAL_SCALE = 35;   // extra exaggeration on top of the baked 8x VERT_EXAG (was 15)
const BASE_VERT_EXAG = 8;        // matches the convention baked into the OBJ export

// Rain particle count/size/opacity are deliberately restrained: 1500 large (4.5px), bright
// (0.85 opacity) particles compete for attention with the tracer flow underneath and read as
// visual noise rather than a legible cue. Tuned for "clearly raining, not overwhelming."
const N_RAIN = 700;               // was 1500 (before that, 900)
const FALL_SPEED = 45;           // scene units/s — slower than the full-AOI rainParticles.js
                                  // (180) since this test area is only ~160m across; a fast
                                  // fall reads as a blur at this zoom level.
const MAX_INTENSITY_MM_HR = 150;

// Do NOT pass the true physical rain duration (summary.rain_duration_min * 60 = 240s) to
// tracerFlow.setRainSpread(). Doing so makes dropletFlow.js stagger each of the 2,500
// tracers' start times across a 240-real-second window; combined with each particle's own
// ~18s of travel time, the full animation cycle was ~258 real seconds long. At 1x playback the
// overwhelming majority of tracers simply hadn't reached their start time within any normal
// viewing window — they sat frozen at their sky-fall origin, reading as "the colored droplets
// don't move at all, only the falling rain does" (confirmed: even at 8x speed for 40+ real
// seconds, most tracers were still visibly static). The old standalone droplet layer never hit
// this because its rain-spread was a small user-adjustable demo value, not the true physical
// rain duration. Fix: compress the stagger to a demo-legible window — the sorted-by-real-
// start-time export order (see run_flow_tracers in mesh_shallow_water.py) still makes "who
// arrives first" meaningful, just compressed in time, same spirit as this file's other
// demo-legibility tuning (DEPTH_VISUAL_SCALE etc. above).
const DEMO_TRACER_SPREAD_S = 10;

// A second issue, distinct from the stagger fix above: tracers can appear to move only
// vertically, following the sky-fall line, with no visible downslope flow.
// Root cause: real, solver-driven horizontal creep after landing is genuinely
// small (median ~4 scene units for the majority "still-moving" tracers) next to the 15m-real
// sky-fall lead-in's ~120 scene-unit drop (15m x the 8x baked-in VERT_EXAG convention) — a ~30x
// scale mismatch, not a stuck/frozen path. First attempted fix — exaggerating each path's
// post-landing (x,z) displacement — was WRONG and got reverted: it moved points to (x,z)
// locations the water never actually reached, visibly crossing over neighboring rooftops and
// the tree canopy the physics mesh doesn't even model ("water cannot flow across a tree
// horizontally," correctly called out). The real per-step positions are constrained to the
// actual mesh topology and must never be rescaled. See dropletFlow.js's COMET_STEPS comment for
// the actual fix used instead (a short real-position trailing streak, not a position rewrite).

function synthticRainRateMmHr(tS, rainDurationS, peakMmHr) {
  const ramp = rainDurationS * 0.15;
  if (tS < ramp) return peakMmHr * (tS / ramp);
  if (tS < rainDurationS - ramp) return peakMmHr;
  if (tS < rainDurationS) return peakMmHr * ((rainDurationS - tS) / ramp);
  return 0.0;
}

// 2026-07-21: replaced with a discrete multi-hue bucket palette matching floodLayer.js's
// Hurricane Ian depthToRGBA() — same exact RGB/alpha values per bucket, just remapped to much
// shallower meter thresholds (real depths here top out ~0.11-0.58m across all 6 rain-intensity
// presets, vs Ian's flood reaching well past 1m). A single-hue brightness ramp is much less
// distinguishable by patch and color than Ian's layer, for an explainable reason:
// human vision reads hue changes far more readily than brightness
// changes of the same hue, and Ian's discrete if/else buckets create visible boundary lines
// between depth classes (a de facto contour map) that a continuous ramp can't produce no matter
// how it's tuned. One shared scale across all 6 site/intensity presets (not rescaled per
// preset) so switching Low->High visibly shows MORE area pushing into deeper buckets, rather
// than each preset independently stretching to "look equally colorful."
// No re-simulation needed for this change — h is already-computed data; only the color mapping
// changed, same category as the earlier SAT_DEPTH/DEPTH_VISUAL_SCALE demo-legibility tuning.
// Alpha is baked into RGB brightness (not a real alpha channel) because this mesh uses additive
// blending (dry -> black -> invisible), not standard alpha blending — see class comment above.
// Without BRIGHTNESS_SCALE the palette is too bright to read — a real optical issue, not a
// preference call. Additive blending means these colors get added directly on top of the
// already-lit point cloud/terrain beneath them (no alpha-multiply against the destination), and
// the mid-range buckets (sky-blue/strong-blue) that cover most of the *typical* wet area — not
// just isolated peaks — were pushing toward 0.8+ in the blue channel. Over a large mesh area
// that reads as glare/wash-out, not color. BRIGHTNESS_SCALE pulls the whole palette down
// uniformly (preserves the relative hue/intensity differences between buckets — the actual
// thing that makes patches distinguishable — while keeping peak brightness in a comfortable
// range under additive blending).
const BRIGHTNESS_SCALE = 0.45;

function depthColor(depthM) {
  // "Trace shimmer" bucket (was: depthM < 0.002, color 100/220/255 — high across all three
  // channels, reads as near-white) was removed: any barely-wet cell triggered
  // it, and across a large mesh area that washed the ground pale/white and made it hard to
  // see. Below its old 0.002m threshold now just renders as dry (invisible) instead — the
  // remaining 5 tiers (bright cyan through indigo) keep their original thresholds/colors
  // unchanged, "bright cyan" is just the new first visible tier instead of the 2nd.
  if (depthM < 0.002) return [0, 0, 0];
  let r, g, b, a;
  if      (depthM < 0.012) { r =  20; g = 190; b = 255; a = 160; }  // bright cyan (first tier)
  else if (depthM < 0.04)  { r =   0; g = 140; b = 255; a = 210; }  // vivid sky-blue
  else if (depthM < 0.12)  { r =   0; g =  80; b = 240; a = 235; }  // strong blue
  else if (depthM < 0.30)  { r =   0; g =  40; b = 210; a = 245; }  // deep blue
  else                     { r =  30; g =   0; b = 170; a = 250; }  // indigo/violet
  const k = (a / 255) * BRIGHTNESS_SCALE;
  return [(r / 255) * k, (g / 255) * k, (b / 255) * k];
}

async function loadFlatMesh(url) {
  const loader = new OBJLoader();
  const obj = await loader.loadAsync(url);
  let geo = null;
  obj.traverse(child => { if (child.isMesh) geo = child.geometry; });
  if (geo.index) geo = geo.toNonIndexed();
  return geo;
}

async function loadFrames(url) {
  const buf = await fetch(url).then(r => r.arrayBuffer());
  const dv = new DataView(buf);
  const magic = String.fromCharCode(dv.getUint8(0), dv.getUint8(1), dv.getUint8(2), dv.getUint8(3));
  if (magic !== 'MSWE') throw new Error(`${url}: bad magic "${magic}"`);
  let off = 4;
  const nTri = dv.getUint32(off, true); off += 4;
  const nFrames = dv.getUint32(off, true); off += 4;
  const isRoof = new Uint8Array(buf.slice(off, off + nTri)); off += nTri;
  const times = new Float32Array(buf.slice(off, off + nFrames * 4)); off += nFrames * 4;
  const frames = [];
  for (let f = 0; f < nFrames; f++) {
    frames.push(new Float32Array(buf.slice(off, off + nTri * 4)));
    off += nTri * 4;
  }
  return { nTri, nFrames, isRoof, times, frames };
}

async function loadHeightmap(url) {
  const buf = await fetch(url).then(r => r.arrayBuffer());
  const dv = new DataView(buf);
  const magic = String.fromCharCode(dv.getUint8(0), dv.getUint8(1), dv.getUint8(2), dv.getUint8(3));
  if (magic !== 'HMAP') throw new Error(`${url}: bad magic "${magic}"`);
  const nx = dv.getInt32(4, true);
  const ny = dv.getInt32(8, true);
  const sx0 = dv.getFloat32(12, true), sx1 = dv.getFloat32(16, true);
  const sz0 = dv.getFloat32(20, true), sz1 = dv.getFloat32(24, true);
  const grid = new Float32Array(buf.slice(28, 28 + nx * ny * 4));
  return { nx, ny, sx0, sx1, sz0, sz1, grid };
}

export async function createMeshShallowWater(urls = {}) {
  const meshUrl = urls.mesh || '/data/dense_test_area_mesh.obj';
  const framesUrl = urls.frames || '/data/swe_mesh_frames.bin';
  const heightmapUrl = urls.heightmap || '/data/swe_surface_heightmap.bin';
  const summaryUrl = urls.summary || '/data/swe_mesh_summary.json';
  const tracersUrl = urls.tracers || '/data/flow_tracer_paths.bin';

  const [baseGeo, frameData, hmap, summary, tracerFlow] = await Promise.all([
    loadFlatMesh(meshUrl), loadFrames(framesUrl), loadHeightmap(heightmapUrl),
    fetch(summaryUrl).then(r => r.json()), createDropletFlow(tracersUrl),
  ]);
  // Paths were exported in ascending real-start-time order specifically so this linear,
  // index-based stagger approximates the real rain-weighted arrival distribution — see
  // run_flow_tracers's sort comment in mesh_shallow_water.py. Spread is compressed to a
  // demo-legible window (DEMO_TRACER_SPREAD_S), NOT the true rain_duration_min — see that
  // constant's comment for the "droplets don't move" bug this fixes.
  tracerFlow.setRainSpread(DEMO_TRACER_SPREAD_S);

  const group = new THREE.Group();
  group.name = 'Mesh Shallow-Water Simulation';
  group.add(tracerFlow.mesh);

  // Tracks whatever exaggeration `basePos`/`hmap.grid`/`topY` are CURRENTLY scaled to — starts
  // at BASE_VERT_EXAG (8, the OBJ/heightmap export convention) and is updated by setExag()
  // below. Real bug this fixes (2026-07-21): applyFrame() rebuilds vertex Y from `basePos`
  // every time the visible frame changes (i.e. constantly during playback) — a ONE-TIME
  // rescaleY() call from main.js at load time got immediately undone the moment the next frame
  // arrived, since applyFrame always reset from the original unscaled basePos. The film would
  // render correctly for a moment then snap back to 8x scale — "floats in the air at a
  // different exaggeration" — every time. setExag() rescales the actual source arrays in
  // place instead of relying on an external one-shot mesh transform.
  let currentVertExag = BASE_VERT_EXAG;

  // ── Depth-film overlay ──────────────────────────────────────────────────────
  const basePos = baseGeo.attributes.position.array;   // (nTri*3 verts) * 3 floats, y already
                                                          // has BASE_VERT_EXAG baked in
  const filmGeo = new THREE.BufferGeometry();
  const filmPos = new Float32Array(basePos.length);
  filmPos.set(basePos);
  const filmColor = new Float32Array(basePos.length);
  filmGeo.setAttribute('position', new THREE.BufferAttribute(filmPos, 3));
  filmGeo.setAttribute('color', new THREE.BufferAttribute(filmColor, 3));
  const filmMat = new THREE.MeshBasicMaterial({
    vertexColors: true, transparent: true, blending: THREE.AdditiveBlending,
    depthWrite: false, side: THREE.DoubleSide,
  });
  const filmMesh = new THREE.Mesh(filmGeo, filmMat);
  filmMesh.name = 'Mesh SWE depth film';
  group.add(filmMesh);

  let lastFrame = null;
  function applyFrame(depthPerTri) {
    lastFrame = depthPerTri;
    const pos = filmGeo.attributes.position.array;
    const col = filmGeo.attributes.color.array;
    for (let t = 0; t < depthPerTri.length; t++) {
      const d = depthPerTri[t];
      const [r, g, b] = depthColor(d);
      const yOff = d * currentVertExag * DEPTH_VISUAL_SCALE;
      for (let k = 0; k < 3; k++) {
        const vi = (t * 3 + k);
        pos[vi * 3 + 1] = basePos[vi * 3 + 1] + yOff;
        col[vi * 3] = r; col[vi * 3 + 1] = g; col[vi * 3 + 2] = b;
      }
    }
    filmGeo.attributes.position.needsUpdate = true;
    filmGeo.attributes.color.needsUpdate = true;
  }
  applyFrame(frameData.frames[0]);

  // ── Falling rain particles, landing on the real surface height ─────────────
  const rainDurationS = summary.rain_duration_min * 60;
  const peakMmHr = summary.peak_rain_mm_hr;
  const loopDurationS = frameData.times[frameData.times.length - 1] || summary.total_min * 60;
  // Max surface height from the heightmap grid — NOT `Math.max(...basePos)`, which would
  // spread a multi-hundred-thousand-element typed array as call args and blow the stack.
  function computeTopY() {
    let maxSurfaceY = -Infinity;
    for (let k = 0; k < hmap.grid.length; k++) if (hmap.grid[k] > maxSurfaceY) maxSurfaceY = hmap.grid[k];
    return maxSurfaceY + 40;
  }
  let topY = computeTopY();

  function heightAt(sx, sz) {
    const { nx, ny, sx0, sx1, sz0, sz1, grid } = hmap;
    const fx = ((sx - sx0) / (sx1 - sx0)) * (nx - 1);
    const fz = ((sz - sz0) / (sz1 - sz0)) * (ny - 1);
    if (!isFinite(fx) || !isFinite(fz)) return 0;
    const ix = Math.min(Math.max(Math.round(fx), 0), nx - 1);
    const iz = Math.min(Math.max(Math.round(fz), 0), ny - 1);
    return grid[iz * nx + ix];
  }

  function randomXZ() {
    const { sx0, sx1, sz0, sz1 } = hmap;
    return [sx0 + Math.random() * (sx1 - sx0), sz0 + Math.random() * (sz1 - sz0)];
  }

  const rainPos = new Float32Array(N_RAIN * 3);
  for (let i = 0; i < N_RAIN; i++) {
    const [x, z] = randomXZ();
    rainPos[i * 3] = x; rainPos[i * 3 + 1] = topY - Math.random() * (topY - 5); rainPos[i * 3 + 2] = z;
  }
  const rainGeo = new THREE.BufferGeometry();
  rainGeo.setAttribute('position', new THREE.BufferAttribute(rainPos, 3));
  rainGeo.setDrawRange(0, 0);
  const rainMat = new THREE.PointsMaterial({
    color: 0x99d5ff, size: 3.0, transparent: true, opacity: 0.55,   // was 4.5/0.85 (before that 3.2/0.7)
    sizeAttenuation: true, depthWrite: false,
  });
  const rainPoints = new THREE.Points(rainGeo, rainMat);
  rainPoints.name = 'Mesh SWE falling rain';
  group.add(rainPoints);

  // ── Playback ─────────────────────────────────────────────────────────────
  let speed = 1.0;
  let elapsed = 0;
  let lastFrameIndex = 0;
  function setSpeed(x) { speed = x; tracerFlow.setSpeed(x); }

  // Same rescale-in-place technique main.js's generic rescaleY() uses, applied here to the
  // tracer sub-layer specifically. dropletFlow.js's own paths array is safe to rescale this
  // way — unlike the depth film, it never had a snap-back bug, because its playback reads
  // straight from this same array every tick rather than from a separate stale copy.
  function rescaleTracerY(ratio) {
    tracerFlow.mesh.traverse(child => {
      const geo = child.geometry;
      if (geo && geo.attributes && geo.attributes.position) {
        const pos = geo.attributes.position;
        for (let i = 0; i < pos.count; i++) pos.setY(i, pos.getY(i) * ratio);
        pos.needsUpdate = true;
      }
    });
  }

  // Rescales every exaggeration-baked source array IN PLACE (not a one-shot mesh transform —
  // see the currentVertExag comment above for why that broke). Called by main.js both at
  // initial load (to match whatever the live slider is already at, since the default is no
  // longer the same as the 8x baked-in convention) and on every subsequent slider move.
  function setExag(newExag) {
    const ratio = newExag / currentVertExag;
    if (ratio === 1) return;
    for (let i = 1; i < basePos.length; i += 3) basePos[i] *= ratio;   // Y components only
    for (let i = 0; i < hmap.grid.length; i++) hmap.grid[i] *= ratio;
    topY = computeTopY();
    const pos = rainGeo.attributes.position.array;
    for (let i = 1; i < pos.length; i += 3) pos[i] *= ratio;           // rescale in-flight rain
    rainGeo.attributes.position.needsUpdate = true;
    rescaleTracerY(ratio);
    currentVertExag = newExag;
    if (lastFrame) applyFrame(lastFrame);   // re-apply now instead of waiting for next frame change
  }

  function tick(dt) {
    if (!group.visible) return;
    tracerFlow.tick(dt);   // before any early return below — must always run every tick
    elapsed = (elapsed + dt * speed) % loopDurationS;

    // Nearest depth frame at or before `elapsed`. applyFrame() walks all 219k triangles,
    // so only call it when the target frame actually changed — at 60fps vs. ~3s between
    // saved frames, most ticks would otherwise redo the same update for no visual change.
    let fi = 0;
    while (fi < frameData.times.length - 1 && frameData.times[fi + 1] <= elapsed) fi++;
    if (fi !== lastFrameIndex) { applyFrame(frameData.frames[fi]); lastFrameIndex = fi; }

    // Rain particle count from the same synthetic hyetograph the solver used.
    const rateMmHr = synthticRainRateMmHr(elapsed, rainDurationS, peakMmHr);
    const activeCount = Math.round(Math.min(rateMmHr / MAX_INTENSITY_MM_HR, 1.0) * N_RAIN);
    rainPoints.visible = activeCount > 0;
    rainGeo.setDrawRange(0, activeCount);
    if (activeCount === 0) return;

    const pos = rainGeo.attributes.position.array;
    const fallDist = FALL_SPEED * dt * speed;
    for (let i = 0; i < activeCount; i++) {
      pos[i * 3 + 1] -= fallDist;
      const surfY = heightAt(pos[i * 3], pos[i * 3 + 2]);
      if (pos[i * 3 + 1] <= surfY) {
        const [x, z] = randomXZ();
        pos[i * 3] = x; pos[i * 3 + 1] = topY; pos[i * 3 + 2] = z;
      }
    }
    rainGeo.attributes.position.needsUpdate = true;
  }

  // See dropletFlow.js's dispose() — same reason: the 2026-07-21 rain-intensity re-simulation
  // feature swaps in a freshly-fetched instance (up to 143MB of frame data plus the tracer/rain
  // geometries) on every "Apply", and without releasing the old one's GPU buffers each apply
  // would leak.
  function dispose() {
    group.parent?.remove(group);
    filmGeo.dispose(); filmMat.dispose();
    rainGeo.dispose(); rainMat.dispose();
    tracerFlow.dispose();
  }

  return { group, tick, setSpeed, setExag, dispose };
}
